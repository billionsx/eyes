#!/usr/bin/env bash
# BXE · хроника: коммит состояния в репозиторий (основной канал наблюдаемости).
# Использование: bin/chronicle.sh "сообщение" путь [путь...]
# Пустой дифф — не ошибка. Пуш с ретраями: чужой прогон мог опередить.
set -u
cd "$(dirname "$0")/.." || exit 2
MSG="${1:?нужно сообщение}"
shift
# Драйвер слияния складов: столкновение по адресу решается объединением.
# Без него `-X theirs` молча выбрасывал страницы другого писателя — для
# журнала терпимо, для склада знаний это потеря добытого.
git config merge.corpusunion.name "объединение склада по адресу"
git config merge.corpusunion.driver "python3 bin/corpus_merge.py %O %A %B"
git config user.name "eyes"
git config user.email "ceo@billionsx.com"
git add "$@" 2>/dev/null || true
if git diff --cached --quiet; then
  echo "изменений нет — хроника чиста"
  exit 0
fi
git commit -q -m "$MSG"
# ВАЖНО: без `-X theirs`.
#
# Родословная (03.08.2026). Стратегия `-X theirs` при перебазировании
# означает «в любом столкновении оставить СВОЮ сторону» — то есть молча
# выбросить работу другого писателя. Для склада знаний это уже чинили
# драйвером объединения, но столкновение бывает не только в складе: в тот
# день ежедневный прогон стёр из bin/eyes.py чужие проверки суда — не
# конфликтом, а перезаписью. Суд остался зелёным: проверок, которые могли
# бы покраснеть, в файле больше не было.
#
# Молчаливый выбор стороны дороже потерянной записи. Хроника — вещь
# восстановимая: следующий прогон запишет её снова. Чужая работа —
# невосстановима. Поэтому столкновение вне склада ОСТАНАВЛИВАЕТ запись и
# кричит об этом, а не решается за другого.
for i in 1 2 3 4 5 6; do
  if git push -q; then
    echo "хроника записана: $(git rev-parse --short HEAD)"
    exit 0
  fi
  if ! git pull --rebase -q; then
    # СТОЛКНОВЕНИЕ БЫВАЕТ ДВУХ РОДОВ (05.08.2026).
    #
    # В ИСТОЧНИКЕ — чужую сторону не восстановить, и запись обязана встать.
    # В ПРОИЗВОДНОМ — файл собирается прогоном, терять нечего: достаточно
    # пересобрать. Прежнее правило не различало их и остановило запись из-за
    # столкновения в перегенерируемом эфире — вместе с ней погиб ДОКУМЕНТ ОБ
    # ОТКАЗЕ СУДА, ровно тогда, когда он был нужнее всего.
    #
    # Список производных поимённый (bin/derived.py) и под судом: глухое «всё
    # в этой папке производно» однажды проглотит источник.
    CONFLICTS=$(git diff --name-only --diff-filter=U)
    if python3 bin/derived.py --check $CONFLICTS; then
      echo "столкновение только в производных — беру их сторону и пересобираю"
      for f in $CONFLICTS; do git checkout --theirs -- "$f" 2>/dev/null || true; done
      python3 bin/dashboard.py >/dev/null 2>&1 || true
      git add $CONFLICTS 2>/dev/null || true
      if ! GIT_EDITOR=true git rebase --continue >/dev/null 2>&1; then
        git rebase --abort 2>/dev/null || true
        echo "::error::пересборка не сняла столкновение — запись отменена."
        exit 1
      fi
    else
      git rebase --abort 2>/dev/null || true
      echo "::error::хроника НЕ записана: столкновение в ИСТОЧНИКЕ." \
           "Сторона не выбирается молча — запись отменена, работа чужая цела."
      exit 1
    fi
  fi
  sleep 4
done
git push
